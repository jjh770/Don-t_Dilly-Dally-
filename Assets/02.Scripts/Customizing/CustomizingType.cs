/// <summary>
/// 커스터마이징 종류 (8가지)
/// 각 종류는 하나의 슬롯처럼 동작하며, 동일 종류에서는 항상 하나만 선택 가능
/// </summary>
public enum CustomizingType
{
    SkinColor,      // 피부색
    Hat,            // 머리장식
    HairStyle,      // 머리스타일
    Faces,          // 표정
    FaceAccessory,  // 얼굴장식
    Glasses,        // 눈장식 (안경 등)
    Shoes,          // 신발
    Costumes        // 코스튬
}
